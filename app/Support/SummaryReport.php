<?php

namespace App\Support;

use App\Models\Ticket;
use App\Models\TicketSummary;

/**
 * بنية تقرير «دراسة الملف والرأي القانوني» — الوثيقة المختومة التي تُصدَّر PDF.
 *
 * فُصلت عن المتحكّم لأن محتواها **يُدَّعى به**: التقرير يحمل كتلة اعتماد وتوقيع
 * مستشار ونقشاً يشبه QR، فما يُكتب فيه يُقرأ إثباتاً. (والنقش **زخرفيّ لا يُمسح**
 * — انظر `Qr` — فلا يُرافَق بنصٍّ يَعِد بتحقّق.) وكان بديلا الحقلين الفارغين يقولان
 * «تم فحص المرفقات ومطابقتها وفق نظام الإثبات السعودي» و«تم اعتماد الدراسة وإصدار
 * التوصية بالمتابعة» — إثباتُ واقعتين إجرائيّتين لم تقعا، داخل وثيقة مختومة. ومحتوى
 * كهذا لا يُحرَس بقراءة الشيفرة؛ يُحرَس باختبارٍ يقرأ الوثيقة نفسها.
 */
class SummaryReport
{
    /** ما يُكتب حين يخلو الحقل — إعلانُ غيابٍ لا ادّعاءُ إنجاز. */
    public const NO_ATTACHMENT_REVIEW = 'لم يُدرَج فحص المرفقات في هذا الملفّ بعد.';

    public const NO_LEGAL_OPINION = 'لم يُدوَّن الرأي القانونيّ بعد.';

    /**
     * @return array<string,mixed> البنية التي يفهمها `ReportPrint::html`
     */
    public static function doc(Ticket $ticket, TicketSummary $summary, string $clientName, string $lawyerName): array
    {
        return [
            'title' => 'تقرير دراسة الملف والرأي القانوني المبدئي',
            'subtitle' => "التذكرة: {$ticket->number} · {$ticket->type}",
            'ref' => "REF-{$ticket->number}",
            'blocks' => [
                [
                    'title' => 'بيانات القضية والموكل',
                    'cellRows' => [
                        [['رقم التذكرة', $ticket->number], ['اسم العميل', $clientName]],
                        [['نوع القضية', $ticket->type], ['القسم', $ticket->department ?: '—']],
                        [['المستشار المسؤول', $lawyerName], ['حالة الدراسة', $summary->isApproved() ? 'معتمد رسمياً' : 'قيد الدراسة']],
                    ],
                ],
                [
                    'title' => 'أولاً: ملخص موضوع النزاع',
                    'lines' => $summary->case_summary ?: ($ticket->details ?: '—'),
                ],
                [
                    'title' => 'ثانياً: فحص المرفقات والمستندات الثبوتية',
                    'lines' => $summary->attachments_summary ?: self::NO_ATTACHMENT_REVIEW,
                ],
                [
                    'title' => 'ثالثاً: سرد الوقائع التعاقدية والإجرائية',
                    'lines' => $summary->facts ?: '—',
                ],
                [
                    'title' => 'رابعاً: الرأي القانوني المعتمد والتوصيات',
                    'lines' => $summary->key_points ?: self::NO_LEGAL_OPINION,
                ],
            ],
            'approval' => [
                // البذرة مجرّد مُدخَل للنقش الزخرفيّ (`Qr` حتميّ من `crc32`)، وكانت
                // رابط تحقّق `…/verify?ref=…&approved=1` — **ولا مسار تحقّق في المشروع**.
                // فمن يقرأ الوثيقة يظنّ ثمّة صفحةً تُصدّقها. المرجع وحده يكفي بذرةً.
                'qrSeed' => "REF-{$ticket->number}",
                // العنوان يُعلن الاعتماد حين يقع فقط؛ وإلّا فهو ذيلُ إصدارٍ لا توقيع
                'title' => $summary->isApproved() ? 'اعتماد وتوقيع الإدارة العليا' : 'بيانات إصدار الوثيقة',
                'rows' => [
                    // **صفّا الاعتماد يتبعان الاعتماد.** كانا يطبعان اسم المستشار
                    // بوصفه «المعتمد» و**تاريخ اليوم** بوصفه تاريخ اعتماد، لملخّصٍ
                    // لم يُعتمد قطّ (`printSummary` بلا حارس، يكفيه وجود الملخّص).
                    // فتخرج وثيقةٌ تقول في صدرها «قيد الدراسة» وفي ذيلها «معتمدة
                    // وموقّعة من الإدارة العليا بتاريخ اليوم» — والقارئ يصدّق الختم.
                    ['المستشار المعتمد', $summary->isApproved() ? $lawyerName : '— لم يُعتمد بعد —'],
                    ['تاريخ الاعتماد', $summary->approved_at?->format('Y-m-d H:i') ?: '— لم يُعتمد بعد —'],
                    // كان «موثق ومعتمد برقم مرجعي» بجوار رمزٍ **زخرفيّ لا يُمسح**
                    // (انظر توثيق `Qr`) — فيُقرأ ختمَ تحقّقٍ إلكترونيّ ولا جهة تُحقّقه.
                    // والصادق أن يُذكر ما يقع فعلاً: اعتمادٌ داخليّ بمرجع الملفّ.
                    ['المرجع الداخليّ', "REF-{$ticket->number}"],
                ],
            ],
            'note' => 'إشعار سرية: هذا التقرير صادر إلكترونياً من النظام الإداري لمكاتب المحاماة ويخضع للسرية المهنية والمصادقة المعتمدة.',
            'footer' => 'النظام الإداري لمكاتب المحاماة — منظومة المحاماة والاستشارات القانونية بالمملكة العربية السعودية',
        ];
    }
}
