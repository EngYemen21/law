<?php

namespace App\Support;

use Illuminate\Contracts\Database\Query\Builder as BuilderContract;
use Illuminate\Database\Eloquent\Builder as EloquentBuilder;

/**
 * **بحثٌ نصّيّ عربيّ يجد ما يبحث عنه المستخدم** — مصدرٌ واحد للتهريب والتطبيع.
 *
 * ثلاث علل كانت في كلّ مرشّح بحثٍ في التطبيق:
 *
 * ١. **الأرقام العربيّة-الهنديّة.** المراجع مخزَّنة بأرقام لاتينيّة (`SB-2026-1042`)، ومن
 *    يكتب `٢٠٢٦` — وهو ما تكتبه لوحة المفاتيح العربيّة افتراضاً — يحصل على صفر.
 *
 * ٢. **الهمزة والتاء المربوطة والألف المقصورة.** التجميع `utf8mb4_unicode_ci` غير حسّاسٍ
 *    لحالة الأحرف لكنّه حسّاسٌ للتشكيل: `LIKE '%احمد%'` لا يطابق «أحمد»، و«محكمه» لا تجد
 *    «محكمة». والحرفان مختلفان في كلّ تجميع.
 *
 * ٣. **`%` و`_` غير مهرَّبين** في أربعة مرشّحات خادميّة — فبحثٌ يحوي `%` يتحوّل إلى محرف
 *    بدلٍ ويُرجِع الجدول كلّه. (‏`TimelineQuery` وحده كان يهرّبهما.)
 *
 * والتطبيع يقع على **الطرفين**: على ما يكتبه المستخدم وعلى العمود في SQL — إذ لا يكفي
 * تطبيع الإبرة وحدها ما دام المخزون غير مطبَّع. والجداول هنا صغيرة، فكلفةُ `REPLACE`
 * المتداخلة مقبولةٌ ثمناً لبحثٍ يجد.
 */
class SearchText
{
    /**
     * أزواج التطبيع — تُطبَّق على الإبرة وعلى العمود بالترتيب نفسه.
     *
     * التاء المربوطة تُردّ إلى الهاء لا العكس: من يكتب «محكمه» يقصد «محكمة»، ومن يكتب
     * «محكمة» يقصدها — والردّ إلى الأبسط يجعل الاتجاهين يلتقيان.
     *
     * @var array<string, string>
     */
    public const FOLD = [
        'أ' => 'ا', 'إ' => 'ا', 'آ' => 'ا', 'ٱ' => 'ا',
        'ة' => 'ه',
        'ى' => 'ي', 'ئ' => 'ي',
        'ؤ' => 'و',
        'ـ' => '',   // التطويل
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
        // الأرقام الفارسيّة — تصل من بعض لوحات المفاتيح
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
    ];

    /** يطبّع ما كتبه المستخدم: أرقاماً عربيّةً وهمزاتٍ وتاءً مربوطة وتطويلاً. */
    public static function fold(string $raw): string
    {
        return str_replace(array_keys(self::FOLD), array_values(self::FOLD), trim($raw));
    }

    /**
     * الإبرة جاهزةً لـ`LIKE`: مطبَّعةً ومهرَّبةً ومحاطةً بـ`%`.
     *
     * `%` و`_` يُهرَّبان بالشرطة المائلة، وتُصرَّح في `ESCAPE` عند الاستعمال: MySQL يفترضها
     * افتراضاً وsqlite (محرّك الحزمة) بلا محرف تهريبٍ إطلاقاً.
     */
    public static function needle(string $raw): string
    {
        return '%'.str_replace(['\\', '%', '_'], ['\\\\', '\%', '\_'], self::fold($raw)).'%';
    }

    /**
     * **ما يُطبَّق على العمود — الحروف وحدها لا الأرقام.**
     *
     * الأرقام مخزَّنة لاتينيّةً في كلّ مرجع (`SB-2026-1042`)، فتطبيع الإبرة وحده يكفي لها.
     * أمّا الحروف فمخزَّنةٌ كما كتبها المستخدم («أحمد» و«محكمة») فتلزم الطرفين.
     *
     * والتقسيم ليس تجميلاً: الخريطة كاملةً تعني سبعةً وعشرين `REPLACE` متداخلاً لكلّ عمود،
     * وهو ما يتجاوز حدّ محلّل sqlite (`parser stack overflow`) ويُثقل MySQL بلا طائل.
     *
     * والثمن معلَن: قيمةٌ مخزَّنة بأرقامٍ عربيّة-هنديّة لا يجدها بحثٌ بأرقامٍ لاتينيّة — ولا
     * يكتب التطبيقُ شيئاً كذلك.
     *
     * @var array<string, string>
     */
    public const LETTER_FOLD = [
        'أ' => 'ا', 'إ' => 'ا', 'آ' => 'ا', 'ٱ' => 'ا',
        'ة' => 'ه',
        'ى' => 'ي', 'ئ' => 'ي',
        'ؤ' => 'و',
    ];

    /** تعبير SQL يطبّع حروف العمود — وإلّا طابقت الإبرةُ المطبَّعةُ مخزوناً غير مطبَّع. */
    public static function column(string $column): string
    {
        $expr = $column;
        foreach (self::LETTER_FOLD as $from => $to) {
            $expr = "REPLACE({$expr}, '{$from}', '{$to}')";
        }

        return $expr;
    }

    /**
     * يُضيف شرط بحثٍ على عدّة أعمدة — الطريقة الوحيدة التي ينبغي أن يُبنى بها بحثٌ نصّيّ.
     *
     * @param  EloquentBuilder<covariant \Illuminate\Database\Eloquent\Model>|BuilderContract  $query
     * @param  array<int, string>  $columns
     */
    public static function apply($query, array $columns, string $raw): void
    {
        if (trim($raw) === '') {
            return;
        }

        $needle = self::needle($raw);

        $query->where(function ($q) use ($columns, $needle) {
            foreach ($columns as $column) {
                $q->orWhereRaw(self::column($column).' LIKE ? ESCAPE ?', [$needle, '\\']);
            }
        });
    }
}
