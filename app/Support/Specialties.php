<?php

namespace App\Support;

/**
 * التصنيف الموحّد (canonical) لتخصّصات المحامين وأقسام القضايا — مرجع واحد.
 * القائمة نفسها التي يستخدمها المصنّف الذكي في LegalAiService (14 قسماً).
 * يوفّر تطبيعاً خفيفاً يجسر مفردات الأقسام المختلفة (بذور المستخدمين / خريطة SVC الأمامية)
 * حتى تنجح مطابقة تخصّص الاستشارة مع department المحامي رغم اختلاف الصياغة.
 */
class Specialties
{
    /** التخصّصات القانونية المعتمدة (تُعرض للعميل عند حجز الاستشارة). */
    public const ALL = [
        'الاستشارات القانونية',
        'العقود والاتفاقيات',
        'القضايا التجارية',
        'القضايا العمالية',
        'الأحوال الشخصية',
        'التنفيذ',
        'الشركات',
        'الملكية الفكرية',
        'العقارات',
        'البنوك والتمويل',
        'التأمين',
        'الجرائم المعلوماتية',
        'القضايا الجنائية',
        'التركات والأوقاف',
    ];

    /** مرادفات صياغات الأقسام الشائعة → التخصّص المعتمد. */
    private const SYNONYMS = [
        'التجاري' => 'القضايا التجارية',
        'العمالية' => 'القضايا العمالية',
        'العمالي' => 'القضايا العمالية',
        'العقاري' => 'العقارات',
        'الجزائي' => 'القضايا الجنائية',
        'الجنائي' => 'القضايا الجنائية',
        'المالية والمصرفية' => 'البنوك والتمويل',
        'البنوك' => 'البنوك والتمويل',
        'التمويل' => 'البنوك والتمويل',
        'الملكية الفكرية' => 'الملكية الفكرية',
        'المواريث والتركات' => 'التركات والأوقاف',
        'الأوقاف والوصايا' => 'التركات والأوقاف',
        'المواريث' => 'التركات والأوقاف',
        'التركات' => 'التركات والأوقاف',
        'الأحوال الشخصية' => 'الأحوال الشخصية',
        'الشركات والحوكمة' => 'الشركات',
        'العقود' => 'العقود والاتفاقيات',
        'الاستشارات العامة' => 'الاستشارات القانونية',
        'التقنية وحماية البيانات' => 'الجرائم المعلوماتية',
        'التأمين' => 'التأمين',
        'التنفيذ' => 'التنفيذ',
    ];

    /** كل التخصّصات المعتمدة. */
    public static function all(): array
    {
        return self::ALL;
    }

    /** تطبيع صياغة قسم/تخصّص إلى الشكل المعتمد قدر الإمكان (يجرّد «قسم/القسم» ويطبّق المرادفات). */
    public static function normalize(?string $raw): string
    {
        $s = trim((string) $raw);
        if ($s === '') {
            return '';
        }
        // جرّد بادئة «القسم »/«قسم »
        $s = preg_replace('/^(ال)?قسم\s+/u', '', $s) ?: $s;
        $s = trim($s);

        if (in_array($s, self::ALL, true)) {
            return $s;
        }
        if (isset(self::SYNONYMS[$s])) {
            return self::SYNONYMS[$s];
        }
        // مطابقة احتوائية مرنة (يحتوي اسم التخصّص المعتمد أو مرادفه)
        foreach (self::SYNONYMS as $needle => $canon) {
            if (mb_strpos($s, $needle) !== false) {
                return $canon;
            }
        }
        foreach (self::ALL as $canon) {
            if (mb_strpos($s, $canon) !== false || mb_strpos($canon, $s) !== false) {
                return $canon;
            }
        }

        return $s;
    }

    /** هل يطابق تخصّص المحامي التخصّصَ المطلوب (بعد التطبيع)؟ */
    public static function matches(?string $lawyerDept, ?string $specialty): bool
    {
        $a = self::normalize($lawyerDept);
        $b = self::normalize($specialty);

        return $a !== '' && $a === $b;
    }
}
