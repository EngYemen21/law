        ['label' => 'الجلسة', 'status' => 'موعد مؤكد', 'tone' => 'b-green', 'who' => 'ai', 'role' => 'الجلسة', 'msg' => 'تم تأكيد موعد الجلسة. تُوثّق الجلسة ويُعدّ محضرها والتوصيات.'],
