        ['label' => 'الإحالة للقسم', 'status' => 'محالة للقسم القانوني', 'tone' => 'b-blue', 'who' => 'staff', 'role' => 'إحالة', 'msg' => 'تمت إحالة طلبكم إلى القسم القانوني المختص لدراسة الموضوع.'],
