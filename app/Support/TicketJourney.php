/**
 * رحلة معالجة التذكرة — المراحل السبع المتسلسلة (تطابق TKT_LIFE في الواجهة).
 * كل مرحلة: الحالة + لون الشارة + المتحدّث + الدور + نصّ يُضاف للمحادثة.
