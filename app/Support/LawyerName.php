<?php

namespace App\Support;

use App\Models\User;

/**
 * **اسمُ المحامي كما يراه العميل: «الاسمُ الأوّل. الحرفُ الأوّل من الثاني».** (قرار المالك 2026-09-11)
 *
 * كانت شاشاتُ العميل تعرضه على ثلاثة أوجه: صريحاً كاملاً (بطاقات الاستشارة والتذاكر والقضايا)،
 * ومقنَّعاً «أ. م••••د ب••• (مشفّر)» (المواعيد وملفّات PDF)، ومقنَّعاً مرّتين في موضعٍ واحد (الخادم
 * يقنّع ثمّ الواجهة تقنّع ما قنّعه). فالصيغةُ الآن واحدة: «محمد. ب».
 *
 * **ولا يُختصر إلا اسمُ محامٍ حقيقيّ.** الحقلُ نفسه يحمل نوائبَ نصّيّة («المستشار المختصّ»،
 * «لم يُسنَد بعد»، و`EscalateUnassignedTicketJob::SENIOR_LABEL` حين يُرفع الملفّ للإدارة) —
 * واختصارُ أيٍّ منها يُنتج كلاماً بلا معنى. فالمصدرُ هو المستخدمُ المسنَد بدور محامٍ، وما سواه
 * يمرّ كما هو.
 */
final class LawyerName
{
    /** التذكرة مُصعَّدة لا مُسنَدة لمحامٍ — حالةٌ يكتبها النظام في حقل المحامي. مصدرها هنا لأنّها تُقرأ في `forClient`. */
    public const SENIOR = 'الإدارة العليا';

    /** تسمية المسنَد إليه حين لا يكون محامياً موثَّقاً — انظر `assignedTo`. */
    public const SPECIALIST = 'المستشار المختص';

    /**
     * **التسمياتُ التي يكتبها النظام بنفسه في حقل المحامي — لا أسماءَ أشخاص.**
     *
     * وجودُ هذه القائمة هو ما يفرّق بين حالةٍ صادقة تصل العميل («الإدارة العليا» لملفٍّ
     * مُصعَّد) ونصٍّ حرٍّ لا يمكن التحقّق أنّه محامٍ فلا يُعرض. وهي مغلقة عمداً: ما لم
     * يكتبه النظام من ثوابته ليس تسميةً.
     */
    public const PLACEHOLDERS = [
        self::SENIOR,
        self::SPECIALIST,
        'المستشار القانوني',
        'المستشار المكلف',
        'بانتظار الإسناد',
        'لم يُسنَد بعد',
    ];

    /** ألقابٌ تسبق الاسم ولا تُعدّ منه. */
    private const TITLES = [
        'أ.', 'أ', 'د.', 'د', 'المحامي', 'المحامية', 'المستشار', 'المستشارة',
        'الأستاذ', 'الأستاذة', 'الدكتور', 'الدكتورة', 'الشيخ',
    ];

    /** «محمد بندر» ⇐ «محمد. ب» · «المحامي محمد بندر» ⇐ «محمد. ب» · «سارة القحطاني» ⇐ «سارة. ق». */
    public static function short(string $name): string
    {
        // «أ.محمد» الملتصقة تُفصل ليُعرف اللقب
        $name = trim((string) preg_replace('/^أ\.(?=\S)/u', 'أ. ', trim($name)));
        $words = preg_split('/\s+/u', $name, -1, PREG_SPLIT_NO_EMPTY) ?: [];

        while (count($words) > 1 && in_array($words[0], self::TITLES, true)) {
            array_shift($words);
        }

        if ($words === []) {
            return $name;
        }
        if (count($words) === 1) {
            return $words[0];
        }

        // «ال» التعريف ليست من الاسم: «القحطاني» ⇐ «ق» لا «ا»
        $second = $words[1];
        if (mb_strlen($second) > 2 && mb_substr($second, 0, 2) === 'ال') {
            $second = mb_substr($second, 2);
        }

        return $words[0].'. '.mb_substr($second, 0, 1);
    }

    /**
     * ما يُعرض للعميل في خانة المحامي: المسنَدُ بدور محامٍ يُختصر، وما سواه (نائبٌ نصّيّ، أو ملفٌّ
     * مرفوعٌ للإدارة) يمرّ كما خُزِّن، والفراغُ يأخذ البديل.
     */
    public static function forClient(?User $assigned, ?string $stored, string $fallback): string
    {
        if ($assigned !== null && $assigned->isLawyer() && trim((string) $assigned->name) !== '') {
            return self::short((string) $assigned->name);
        }

        /*
         * **النصّ الحرّ لا يصل العميل — والتسميةُ تصل.** وهذا جذرُ عائلة تسريب الاسم.
         *
         * كان السطر `return $stored !== '' ? $stored : $fallback;` يمرّر العمود النصّيّ خاماً
         * كلّما غاب المحامي المسنَد، فيُعرض على العميل ما كُتب في الصفّ أيّاً كان.
         *
         * ثمّ حُجب المخزَّن كلّه (2026-09-25) بحجّة تعذّر التمييز نصّاً — **وكان ذلك خطأ**:
         * أسقط «الإدارة العليا» للملفّ المُصعَّد، وهي حالةٌ صادقة يقصد النظام إيصالها، فصار
         * العميل يرى «—» مكان خبرٍ يعنيه. والتمييز ممكنٌ بلا تخمين: النظام لا يكتب في هذا
         * الحقل إلّا اسمَ محامٍ أو واحدةً من `PLACEHOLDERS` المعدودة.
         *
         * فالقاعدة: **اسمُ محامٍ موثَّق يُختصر · وتسميةُ النظام تمرّ · وما سواهما يُحجب.**
         * ولا يُقنَّع المخزَّن بدل حجبه لأنّ تقنيع تسميةٍ يُنتج «المستشار. ا» — عطلاً معكوساً.
         *
         * والطاقم غير معنيّ: `ExecService` وغيرها تقرأ الاسم الكامل
         * من مصادرها — هذه الدالّة للعميل وحده كما يقول اسمها.
         */
        $stored = trim((string) $stored);

        return in_array($stored, self::PLACEHOLDERS, true) ? $stored : $fallback;
    }

    /**
     * **المسنَد إليه داخل نصٍّ يقرؤه العميل** («أُسند ملفّ التنفيذ إلى …») — لا في خانةٍ مستقلّة.
     *
     * رسائل المكتب الآليّة كانت تكتب `$lawyer->name` في متن الرسالة، والمتنُ يُحفظ ويُعرض ويُبثّ كما
     * كُتب: فلا تنفع تسميةُ المُرسِل (`ChatSenderLabel`) ولا تقنيعُ الخانة. فالاسم يُقرَّر لحظة الكتابة
     * من هنا: محامٍ موثَّق يُختصر «محمد. ب»، وحسابٌ غيره (مديرٌ يُسنَد احتياطاً) لا يُسمّى.
     * والطاقم يجد الاسم الكامل في سجلّ الانتقالات والتدقيق — لا في متنٍ يقرؤه العميل.
     */
    public static function assignedTo(?User $account): string
    {
        return self::forClient($account, null, self::SPECIALIST);
    }
}
