<?php

namespace App\Domain\Journey\Enums;

/**
 * حالة الفاتورة المخزّنة («متأخرة» تُشتقّ عند القراءة — `Invoice::liveStatus`).
 *
 * **ثلاثٌ أُضيفت في م٢ ولم يُستبدَل شيء** (ب٦ في خطّة النظام الماليّ): الأربع القديمة تبقى
 * بقيمها النصّيّة نفسها، فلا صفَّ في القاعدة يصير غير مقروء.
 *
 * - **مسوّدة**: صدرت في النظام ولم تُرسَل للعميل بعد — فلا مطالبةَ بها ولا سداد.
 * - **مسدّدة جزئيّاً**: دُفع بعضُها وبقي باقٍ — بنيةً في م٢، وتسجيلُ المبلغ الجزئيّ في م٤.
 * - **دين معدوم**: أُسقطت المطالبة، فتخرج من الذمم ولا تعود تُلاحَق (كان المكتب يطالب
 *   بديونٍ لا تُحصَّل إلى الأبد وتبقى منفوخةً في «المستحقّ»).
 */
enum InvoiceStatus: string
{
    case Draft = 'مسوّدة';
    case Due = 'مستحقة';
    case ProofReview = 'بانتظار مراجعة الإثبات';
    case PartiallyPaid = 'مسدّدة جزئيّاً';
    case Paid = 'مدفوعة';
    case Cancelled = 'ملغاة';
    case WrittenOff = 'دين معدوم';

    /**
     * تقبل دفعةً؟ — الملغاة لا تُحيي شيئاً (ع١، ع٢).
     *
     * **والمسوّدة لا تقبل دفعاً**: لم تُرسَل بعد، فمبلغٌ يصل عليها مالٌ بلا مطالبة. والمسدّدة
     * جزئيّاً تقبل — بقيّتها هي المطالبة القائمة. والمعدومة أُسقطت مطالبتُها، فإحياؤها قرارٌ
     * إداريّ (إصدارٌ جديد) لا دفعةٌ تصل.
     */
    public function isPayable(): bool
    {
        return $this === self::Due || $this === self::ProofReview || $this === self::PartiallyPaid;
    }

    /**
     * **لون شارة الحالة — المصدر الواحد** (نمط `TicketJourney::toneFor` و`CaseJourney::toneFor`).
     *
     * كان اللون مكتوباً حرفاً في تسعة مواضع: `Finance\InvoiceFactory` والانتقالات الثمانية.
     * فشاشةٌ جديدة تحتاج لون حالةٍ لم تُكتب بعد (زرُّ ترشيحٍ بالحالة مثلاً) كانت ستنسخ عاشرةً
     * تتباعد عند أوّل تعديل. الحالة تعرف لونَها، والكاتب يسأل.
     *
     * **و«متأخرة» ليست هنا**: حالةٌ مشتقّةٌ عند القراءة لا مخزَّنة — لونها في `Invoice::liveStatus`.
     */
    public function tone(): string
    {
        return match ($this) {
            self::Draft => 'b-grey',          // لم تُرسَل بعد — لا مطالبةَ تُلوَّن
            self::Due => 'b-amber',           // مطالبةٌ قائمة
            self::ProofReview => 'b-blue',    // الكرةُ في ملعب المراجع لا العميل
            self::PartiallyPaid => 'b-amber', // بقيّتُها مطالبةٌ قائمة، فلونُ المستحقّة
            self::Paid => 'b-green',
            self::Cancelled => 'b-red',
            self::WrittenOff => 'b-grey',     // أُسقطت المطالبة — تخرج من الذمم فتخرج من الألوان الحيّة
        };
    }

    /** @return list<string> */
    public static function values(): array
    {
        return array_map(fn (self $s) => $s->value, self::cases());
    }
}
