<?php

namespace App\Domain\Journey\Enums;

/**
 * **حالة الاجتماع المخزّنة — قائمةٌ مغلقة لا نصوصٌ متناثرة.**
 *
 * كانت الحالات تُقارَن نصوصاً عربيّة في المتحكّم والأوامر المجدولة (`in_array($status, ['منتهٍ', 'ملغى'])`)،
 * فخطأٌ إملائيّ واحد — «منتهي» بدل «منتهٍ» — يُسقط الحارس صامتاً. القيم هنا هي ما في العمود حرفاً
 * بحرف (لا ترحيل)، والمنطق يسأل الحالة عن معناها بدل أن يحفظ قائمتها.
 *
 * والحالة **المعروضة** قد تختلف عن المخزّنة: `Meeting::liveState()` يشتقّ «لم ينعقد» لقادمٍ فات
 * موعده قبل أن يكتبها المجدول — فهذا التعداد للعمود، والعرض لـliveState.
 */
enum MeetingStatus: string
{
    case Upcoming = 'قادم';
    case Live = 'جارٍ';
    case Ended = 'منتهٍ';
    case Cancelled = 'ملغى';
    case Missed = 'لم ينعقد';
    case Postponed = 'مؤجل';
    /** تاريخيّة: لا يكتبها مسارٌ حيّ منذ إلغاء تأكيد العميل — باقيةٌ لسجلّاتٍ قديمة. */
    case AwaitingConfirmation = 'بانتظار التأكيد';

    /**
     * **حالةٌ لا رجعة منها:** لا يُعاد جدولتها ولا تُلغى من جديد، ويمتصّ حارسُ الويبهوك ما يصل بعدها.
     *
     * «لم ينعقد» ليست منها عمداً: اجتماعٌ فات بلا حضور تُعطى له فرصةٌ ثانية بإعادة جدولته،
     * وهو المسار الذي تعرضه صفحة الاجتماع لهذه الحالة بالذات.
     */
    public function isFinal(): bool
    {
        return $this === self::Ended || $this === self::Cancelled;
    }

    /** قراءةٌ متسامحة للعمود — قيمةٌ مجهولة ليست نهائيّة (لا تُغلق باباً على سجلٍّ شاذّ). */
    public static function isFinalValue(?string $value): bool
    {
        return self::tryFrom((string) $value)?->isFinal() ?? false;
    }
}
