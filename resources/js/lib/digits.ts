/**
 * **رقمٌ كما يكتبه المستخدم ← أرقامٌ لاتينيّة بلا فواصل** — المصدر الواحد لحقول المبالغ.
 *
 * «25,000» والأرقام العربيّة-الهنديّة (١٥٠٠٠٠) والفارسيّة كانت تُرسَل كما كُتبت فيردّها `integer`
 * في الخادم، أو يرفضها فحص الحقل قبل الإرسال فيبقى الزرّ معطّلاً بلا سببٍ يفهمه المستخدم.
 */
export function normalizeDigits(raw: string): string {
  return raw
    .replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
    .replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
    .replace(/[,،٫٬\s]/g, '')
    .trim();
}
